"""
==============================================================================
SMTP Emergency Email Notification Channel (Phase 3)
==============================================================================
Provides automated dispatch of emergency flood and drought advisories:
- Standard library smtplib with TLS/SSL encryption support.
- Configurable via SMTP_HOST, SMTP_PORT, SMTP_USER, SMTP_PASS, SMTP_FROM.
- Safe zero-cost fallback: if unconfigured or host unreachable, saves formatted
  HTML email to mock log for verification and testing.
- Includes emergency action guidance, telemetry table, and NDMA disclaimer.
==============================================================================
"""

import os
import smtplib
import logging
from datetime import datetime
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from typing import Dict, Any, Optional, List

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger("EmailAlertNotifier")

NDMA_DISCLAIMER = (
    "STATUTORY LEGAL NOTICE: This early warning advisory was generated by an automated "
    "hydro-informatics machine learning system for emergency preparedness decision support. "
    "All alerts must be verified against Central Water Commission (CWC) gauge telemetry and "
    "State Emergency Operation Centre (SEOC) directives prior to statutory public actions."
)


class EmailAlertNotifier:
    """
    Constructs and sends emergency incident advisory emails with rich HTML styling.
    """

    def __init__(
        self,
        smtp_host: Optional[str] = None,
        smtp_port: Optional[int] = None,
        smtp_user: Optional[str] = None,
        smtp_pass: Optional[str] = None,
        smtp_from: Optional[str] = None,
        recipients: Optional[List[str]] = None
    ):
        self.smtp_host = smtp_host or os.getenv("SMTP_HOST")
        self.smtp_port = smtp_port or int(os.getenv("SMTP_PORT", "587"))
        self.smtp_user = smtp_user or os.getenv("SMTP_USER")
        self.smtp_pass = smtp_pass or os.getenv("SMTP_PASS")
        self.smtp_from = smtp_from or os.getenv("SMTP_FROM", "alerts@eews-india.org")

        env_recipients = os.getenv("ALERT_EMAIL_RECIPIENTS", "")
        self.recipients = recipients or ([r.strip() for r in env_recipients.split(",") if r.strip()] if env_recipients else [])
        self.is_configured = bool(self.smtp_host and self.smtp_user and self.smtp_pass and self.recipients)
        self.dispatch_history: List[Dict[str, Any]] = []

    def build_html_email(self, alert_data: Dict[str, Any]) -> str:
        """
        Builds responsive HTML emergency incident dossier email.
        """
        tier = alert_data.get("tier", "HIGH").upper()
        hazard_type = alert_data.get("hazard_type", "flood").upper()
        region_id = alert_data.get("region_id", "406008")
        region_name = alert_data.get("region_name", f"Catchment {region_id}")
        lead_time = alert_data.get("lead_time_h", 48)
        prob = alert_data.get("probability_calibrated", alert_data.get("calibrated_prob", 0.0))
        spei = alert_data.get("spei_forecast", alert_data.get("forecast_index", "N/A"))
        action = alert_data.get("recommended_action", "Initiate localized emergency staging.")
        issued_at = alert_data.get("issued_at", datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC"))

        # Visual color palette
        color_map = {
            "CRITICAL": {"bg": "#7f1d1d", "banner": "#dc2626", "badge": "CRITICAL EMERGENCY"},
            "HIGH": {"bg": "#7c2d12", "banner": "#ea580c", "badge": "HIGH WARNING"},
            "MODERATE": {"bg": "#713f12", "banner": "#ca8a04", "badge": "MODERATE WATCH"},
            "LOW": {"bg": "#14532d", "banner": "#16a34a", "badge": "LOW MONITORING"}
        }
        scheme = color_map.get(tier, color_map["HIGH"])

        prob_str = f"{prob * 100:.1f}%" if isinstance(prob, (int, float)) else str(prob)
        spei_str = f"{spei:.2f}" if isinstance(spei, (int, float)) else str(spei)

        html = f"""
        <!DOCTYPE html>
        <html>
        <head>
          <meta charset="utf-8">
          <style>
            body {{ font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; background-color: #0f172a; color: #f8fafc; margin: 0; padding: 20px; }}
            .container {{ max-width: 650px; margin: 0 auto; background: #1e293b; border-radius: 8px; overflow: hidden; border: 1px solid #334155; }}
            .banner {{ background-color: {scheme['banner']}; padding: 18px 24px; text-align: left; }}
            .banner h1 {{ margin: 0; font-size: 20px; color: #ffffff; letter-spacing: 0.5px; text-transform: uppercase; }}
            .content {{ padding: 24px; }}
            .badge {{ display: inline-block; padding: 4px 10px; font-weight: bold; border-radius: 4px; font-size: 13px; background-color: {scheme['banner']}; color: #ffffff; }}
            table {{ width: 100%; border-collapse: collapse; margin: 18px 0; background: #0f172a; border-radius: 6px; overflow: hidden; }}
            th, td {{ padding: 10px 14px; text-align: left; border-bottom: 1px solid #334155; font-size: 14px; }}
            th {{ background: #1e293b; color: #94a3b8; font-weight: 600; width: 40%; }}
            td {{ color: #e2e8f0; font-weight: 500; }}
            .action-box {{ background: rgba(220, 38, 38, 0.1); border-left: 4px solid {scheme['banner']}; padding: 14px 18px; margin: 18px 0; border-radius: 0 4px 4px 0; }}
            .footer {{ background: #0f172a; padding: 16px 24px; font-size: 11px; color: #64748b; line-height: 1.5; border-top: 1px solid #334155; }}
          </style>
        </head>
        <body>
          <div class="container">
            <div class="banner">
              <h1>🚨 {scheme['badge']} &bull; {hazard_type}</h1>
            </div>
            <div class="content">
              <p style="font-size: 15px; margin-top: 0;">An automated hydro-meteorological early warning alert has been triggered for the following Indian catchment area:</p>
              
              <table>
                <tr><th>Basin / Sub-basin</th><td><strong>{region_name}</strong> (HYBAS: {region_id})</td></tr>
                <tr><th>Hazard Classification</th><td>{hazard_type} Forecast</td></tr>
                <tr><th>Alert Tier</th><td><span class="badge">{tier}</span></td></tr>
                <tr><th>Forecast Horizon</th><td>+{lead_time} Hours Lead Time</td></tr>
                <tr><th>Calibrated Flood Probability</th><td><strong>{prob_str}</strong></td></tr>
                <tr><th>Drought SPEI Z-Score</th><td>{spei_str}</td></tr>
                <tr><th>Advisory Issue Time</th><td>{issued_at}</td></tr>
              </table>

              <div class="action-box">
                <strong style="color: #fca5a5;">Mandatory Recommended Protocol:</strong>
                <p style="margin: 6px 0 0 0; color: #f8fafc; font-size: 14px;">{action}</p>
              </div>

              <p style="font-size: 13px; color: #94a3b8;">Full hydrological GIS layers and physical terrain routing vectors are accessible via the platform dashboard.</p>
            </div>
            <div class="footer">
              <p style="margin: 0;"><strong>CWC / NDMA Guidelines Compliance</strong></p>
              <p style="margin: 4px 0 0 0;">{NDMA_DISCLAIMER}</p>
            </div>
          </div>
        </body>
        </html>
        """
        return html

    def send_alert(self, alert_data: Dict[str, Any], recipients: Optional[List[str]] = None) -> Dict[str, Any]:
        """
        Transmits HTML alert via SMTP or logs in mock mode.
        """
        target_recipients = recipients or self.recipients or ["emergency-desk@ndma.gov.in"]
        alert_id = alert_data.get("id", str(datetime.utcnow().timestamp()))
        tier = alert_data.get("tier", "HIGH").upper()
        hazard_type = alert_data.get("hazard_type", "flood").upper()
        region_id = alert_data.get("region_id", "406008")

        subject = f"[EEWS {tier} ADVISORY] {hazard_type.capitalize()} Alert for Catchment {region_id}"
        html_body = self.build_html_email(alert_data)

        receipt: Dict[str, Any] = {
            "channel": "email",
            "alert_id": alert_id,
            "region_id": region_id,
            "tier": tier,
            "recipients_count": len(target_recipients),
            "timestamp": datetime.utcnow().isoformat(),
            "subject": subject,
            "html_length": len(html_body)
        }

        if not self.is_configured:
            receipt["status"] = "MOCK_LOGGED"
            receipt["notes"] = "SMTP_HOST or credentials unset; captured in mock log."
            logger.info(f"[Email MOCK DISPATCH] Alert {alert_id} recorded for {len(target_recipients)} recipient(s).")
            self.dispatch_history.append(receipt)
            return receipt

        # Real SMTP delivery
        try:
            msg = MIMEMultipart("alternative")
            msg["Subject"] = subject
            msg["From"] = self.smtp_from
            msg["To"] = ", ".join(target_recipients)
            msg.attach(MIMEText(html_body, "html"))

            with smtplib.SMTP(self.smtp_host, self.smtp_port, timeout=10.0) as server:
                server.starttls()
                server.login(self.smtp_user, self.smtp_pass)
                server.sendmail(self.smtp_from, target_recipients, msg.as_string())

            receipt["status"] = "DELIVERED"
            logger.info(f"[Email DELIVERED] Dispatched to {target_recipients}")
        except Exception as e:
            receipt["status"] = "FAILED"
            receipt["error"] = str(e)
            logger.warning(f"[Email FAILED] {e}. Falling back to mock dispatch record.")

        self.dispatch_history.append(receipt)
        return receipt

